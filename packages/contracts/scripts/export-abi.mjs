import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const root = path.join(__dirname, '..')
const artifactPath = path.join(
  root,
  'artifacts/contracts/BeamFinance.sol/BeamFinance.json',
)
const outDir = path.join(root, 'abi')
const outFile = path.join(outDir, 'BeamFinance.json')

const artifact = JSON.parse(fs.readFileSync(artifactPath, 'utf8'))
fs.mkdirSync(outDir, { recursive: true })
fs.writeFileSync(outFile, `${JSON.stringify(artifact.abi, null, 2)}\n`)
console.log('Wrote', outFile)

const tsOut = path.join(outDir, 'BeamFinance.ts')
const tsHeader = `// Generated by scripts/export-abi.mjs — do not edit

`

fs.writeFileSync(
  tsOut,
  `${tsHeader}export const beamFinanceAbi = ${JSON.stringify(artifact.abi, null, 2)} as const
`,
)
console.log('Wrote', tsOut)
